console.log('2. Migrating data rows from SQLite to AWS RDS...');

for (const table of TABLES) {
  const rows = sqlite.all(`SELECT * FROM ${table}`);
  if (rows.length === 0) {
    console.log(`   ${table.padEnd(20)}: 0 rows (skipped)`);
    continue;
  }

  // Get columns from first row
  const cols = Object.keys(rows[0]);
  const colList = cols.map(c => `"${c}"`).join(', ');

  // Disable FK check while copying or use ON CONFLICT DO NOTHING
  await pgClient.query('BEGIN');
  try {
    // Truncate existing rows in this table to prevent duplicate key conflicts
    await pgClient.query(`TRUNCATE TABLE "${table}" RESTART IDENTITY CASCADE`);

    // Insert rows in batches of 500
    const BATCH_SIZE = 500;
    for (let i = 0; i < rows.length; i += BATCH_SIZE) {
      const batch = rows.slice(i, i + BATCH_SIZE);
      const valPlaceholders = [];
      const values = [];

      batch.forEach((row, rIdx) => {
        const rowParams = cols.map((col, cIdx) => `$${rIdx * cols.length + cIdx + 1}`);
        valPlaceholders.push(`(${rowParams.join(', ')})`);
        cols.forEach(col => {
          let v = row[col];
          values.push(v === undefined ? null : v);
        });
      });

      const sql = `INSERT INTO "${table}" (${colList}) VALUES ${valPlaceholders.join(', ')}`;
      await pgClient.query(sql, values);
    }

    // Reset sequence so future auto-increment IDs start after max(id)
    if (cols.includes('id')) {
      await pgClient.query(`
        SELECT setval(
          pg_get_serial_sequence('"${table}"', 'id'),
          COALESCE((SELECT MAX(id) FROM "${table}"), 1)
        )
      `).catch(() => {});
    }

    await pgClient.query('COMMIT');
    console.log(`   ${table.padEnd(20)}: ${rows.length} rows migrated`);
  } catch (err) {
    await pgClient.query('ROLLBACK');
    console.error(`   ERROR migrating ${table}:`, err.message);
  }
}

// 3. Final Verification
console.log('\n--- Final Verification: AWS RDS Row Counts ---');
for (const table of TABLES) {
  const res = await pgClient.query(`SELECT COUNT(*) c FROM "${table}"`);
  console.log(`   ${table.padEnd(20)}: ${res.rows[0].c} rows in RDS`);
}

console.log('\nAll data successfully migrated to Amazon RDS PostgreSQL!');
await pgClient.end();
