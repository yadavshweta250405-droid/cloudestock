// Generates documentation/_generated/API_ENDPOINTS.md and DATABASE_TABLES.md from the real router and the real schema,
// so the reference tables can never drift from the code. Run: npm run docs:generate
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadConfig } from '../backend/src/config.js';
import { createContainer } from '../backend/src/container.js';
import { Router } from '../backend/src/core/router.js';
import { PERMISSIONS, ROLE_LABELS } from '../shared/constants.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'documentation', '_generated'); fs.mkdirSync(out, { recursive: true });
process.env.WARETRACK_QUIET = '1';
const ctx = createContainer(loadConfig({ db: { file: ':memory:' }, storage: { dir: path.join(root, 'database', 'data', 'files-docs') } }));
const router = new Router(); ctx.registerRoutes(router);

// ---- API
const roles = Object.keys(ROLE_LABELS); const short = { admin: 'A', warehouse_manager: 'WM', inventory_manager: 'IM', employee: 'E' };
let md = '<!-- generated by scripts/gen-docs.mjs — do not edit by hand -->\n# API endpoint reference (generated)\n\nRoles: A = Administrator, WM = Warehouse Manager, IM = Inventory Manager, E = Employee.\n\n| Method | Path | Access | Roles |\n|---|---|---|---|\n';
const rows = [['GET', '/api/health', 'public', '—'], ['GET', '/api/events', 'any signed-in user (token in query string, Server-Sent Events)', 'A WM IM E']];
for (const r of router.routes) {
  const perm = r.opts.perm; const allowed = perm ? roles.filter((x) => PERMISSIONS[perm].includes(x)).map((x) => short[x]).join(' ') : r.opts.public ? '—' : 'A WM IM E';
  rows.push([r.method, r.path, r.opts.public ? 'public' : perm ? `\`${perm}\`` : 'any signed-in user', allowed]);
}
md += rows.map((r) => `| ${r.join(' | ')} |`).join('\n') + `\n\n${rows.length} endpoints.\n`;
fs.writeFileSync(path.join(out, 'API_ENDPOINTS.md'), md);

// ---- Database
let db = '<!-- generated by scripts/gen-docs.mjs — do not edit by hand -->\n# Database tables (generated from the live schema)\n\n';
const tables = ctx.db.all(`SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name != 'schema_migrations' ORDER BY name`);
for (const { name } of tables) {
  const cols = ctx.db.all(`PRAGMA table_info(${name})`); const fks = ctx.db.all(`PRAGMA foreign_key_list(${name})`); const idx = ctx.db.all(`PRAGMA index_list(${name})`).filter((i) => !i.name.startsWith('sqlite_autoindex'));
  db += `## ${name}\n\n| Column | Type | Null | Default | Notes |\n|---|---|---|---|---|\n`;
  for (const c of cols) { const fk = fks.find((f) => f.from === c.name); db += `| ${c.name} | ${c.type} | ${c.notnull || c.pk ? 'no' : 'yes'} | ${c.dflt_value ?? ''} | ${[c.pk ? 'PK' : '', fk ? `FK → ${fk.table}.${fk.to} (on delete ${fk.on_delete.toLowerCase()})` : ''].filter(Boolean).join(', ')} |\n`; }
  if (idx.length) db += `\nIndexes: ${idx.map((i) => `\`${i.name}\`${i.unique ? ' (unique)' : ''}`).join(', ')}\n`;
  db += '\n';
}
fs.writeFileSync(path.join(out, 'DATABASE_TABLES.md'), db);
ctx.close(); fs.rmSync(path.join(root, 'database', 'data', 'files-docs'), { recursive: true, force: true });
console.log(`Generated ${rows.length} endpoints and ${tables.length} tables.`);
